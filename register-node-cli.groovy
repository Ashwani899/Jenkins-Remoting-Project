// Registers agent-linux-02 as a permanent SSH-launched node via the Jenkins
// Script Console (Manage Jenkins -> Script Console).
//
// I mostly used the UI for the other three nodes and wrote this one mainly
// to prove to myself I understood the node model well enough to build it
// programmatically - not because click-ops was actually a problem for four
// nodes. For anything beyond a handful of nodes, JCasC is the real answer,
// this was just a learning exercise.
//
// Adjust host/credentialsId/labels before running. credentialsId must
// already exist in the Jenkins credential store (the jenkins-agent-key
// generated by scripts/generate-ssh-keys.sh).

import hudson.model.Node.Mode
import hudson.plugins.sshslaves.SSHLauncher
import hudson.plugins.sshslaves.verifiers.ManuallyTrustedKeyVerificationStrategy
import hudson.slaves.DumbSlave
import hudson.slaves.RetentionStrategy
import jenkins.model.Jenkins

def name        = "agent-linux-02"
def remoteFS    = "/home/jenkins/agent"
def label       = "linux docker"
def host        = "192.168.1.52"
def port        = 22
def credsId     = "jenkins-agent-key"
def executors   = 2

def existing = Jenkins.get().getNode(name)
if (existing != null) {
    println "Node '${name}' already exists, not touching it."
    return
}

def hostKeyStrategy = new ManuallyTrustedKeyVerificationStrategy(true)
def launcher = new SSHLauncher(host, port, credsId, null, null, null, null, null, null, hostKeyStrategy)

def node = new DumbSlave(
    name,
    remoteFS,
    launcher
)
node.setNumExecutors(executors)
node.setLabelString(label)
node.setMode(Mode.NORMAL)
node.setRetentionStrategy(new RetentionStrategy.Always())

Jenkins.get().addNode(node)
println "Registered node '${name}' with labels [${label}]."
